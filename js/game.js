// Reconciles local (guest/localStorage) progress with the server's copy
// right after a successful login/signup. Simple rule: if the account
// already has saved progress on the server, that becomes the source of
// truth (so progress follows the account across devices). Otherwise,
// whatever was played locally as a guest is pushed up to the account.
async function syncAfterLogin() {
  try {
    const remote = await apiFetchProgress();
    if (remote) {
      save = Object.assign(deepClone(DEFAULT_SAVE), remote);
      persistSave();
    } else {
      await apiSaveProgress(save);
    }
  } catch (e) {
    console.warn('Could not sync progress with server:', e.message);
  }
}

// Fire-and-forget push to the server whenever local save changes,
// only when logged in. Never blocks gameplay if the server is
// unreachable — guest/local saving already happened via persistSave().
function syncToServerIfLoggedIn() {
  if (!getToken()) return;
  apiSaveProgress(save).catch(e => console.warn('Cloud save failed:', e.message));
}

