const SAVE_KEY = 'codecrush_save_v1';

const DEFAULT_SAVE = {
  unlockedLevel: 1,
  coins: 60,
  results: {},        // { [levelId]: { stars, score, hintsUsed } }
  wordsDiscovered: [],
  achievements: [],
  dailyStreak: 0,
  lastDaily: null,
  settings: { music: true, sound: true, reducedMotion: false }
};

function deepClone(obj) {
  return JSON.parse(JSON.stringify(obj));
}

let save = loadSave();

function loadSave() {
  try {
    const raw = localStorage.getItem(SAVE_KEY);
    if (!raw) return deepClone(DEFAULT_SAVE);
    const parsed = JSON.parse(raw);
    return Object.assign(deepClone(DEFAULT_SAVE), parsed);
  } catch (e) {
    console.warn('Save failed to load, starting fresh.', e);
    return deepClone(DEFAULT_SAVE);
  }
}

function persistSave() {
  try {
    localStorage.setItem(SAVE_KEY, JSON.stringify(save));
  } catch (e) {
    console.warn('Could not persist save.', e);
  }
  syncToServerIfLoggedIn();
}

