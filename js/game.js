function renderWorldMap() {
  document.getElementById('map-coins').textContent = save.coins;
  const wrap = document.getElementById('map-worlds');
  wrap.innerHTML = '';

  const X_PATTERN = [50, 74, 50, 26]; // percent across the path width, creates the weave
  const Y_SPACING = 100;              // px between level nodes
  const Y_TOP_PAD = 50;

  WORLDS.forEach(world => {
    const levels = LEVELS.filter(l => l.world === world.id);
    const doneCount = levels.filter(l => save.results[l.id]).length;

    const panel = document.createElement('div');
    panel.className = 'world-panel';
    panel.style.background = `linear-gradient(180deg, ${world.bg}, ${world.bg2})`;

    const head = document.createElement('div');
    head.className = 'world-panel-head';
    head.innerHTML = `
      <div>
        <h3>${world.name}</h3>
        <p>${world.subtitle}</p>
      </div>
      <div class="world-progress">${doneCount}/${levels.length}</div>
    `;
    panel.appendChild(head);

    const pathWrap = document.createElement('div');
    pathWrap.className = 'path-wrap';
    const totalHeight = (levels.length - 1) * Y_SPACING + Y_TOP_PAD + 40;
    pathWrap.style.height = totalHeight + 'px';

    const points = levels.map((lvl, i) => ({
      lvl,
      xPct: X_PATTERN[i % X_PATTERN.length],
      y: Y_TOP_PAD + i * Y_SPACING
    }));

    points.forEach(p => {
      const locked = p.lvl.id > save.unlockedLevel;
      const result = save.results[p.lvl.id];
      const isCurrent = p.lvl.id === save.unlockedLevel;

      const btn = document.createElement('button');
      btn.className = 'path-node-btn'
        + (locked ? ' locked' : '')
        + (result ? ' done' : '')
        + (p.lvl.boss ? ' boss' : '')
        + (isCurrent ? ' current' : '');
      btn.style.left = p.xPct + '%';
      btn.style.top = p.y + 'px';
      btn.disabled = locked;

      let inner = locked ? '\uD83D\uDD12' : String(p.lvl.id);
      if (!locked && result) {
        inner += `<span class="node-stars">${'\u2605'.repeat(result.stars)}${'\u2606'.repeat(3 - result.stars)}</span>`;
      } else if (!locked && p.lvl.boss) {
        inner += `<span class="node-stars">\uD83C\uDFC1</span>`;
      }
      btn.innerHTML = inner;
      btn.addEventListener('click', () => startLevel(p.lvl.id));
      pathWrap.appendChild(btn);
    });

    panel.appendChild(pathWrap);
    wrap.appendChild(panel);

    // Draw the road after the panel is in the DOM so we can read its real width.
    const wrapWidth = pathWrap.clientWidth || 340;
    const pixelPoints = points.map(p => ({ x: (p.xPct / 100) * wrapWidth, y: p.y }));
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('class', 'path-road');
    svg.setAttribute('viewBox', `0 0 ${wrapWidth} ${totalHeight}`);
    svg.setAttribute('preserveAspectRatio', 'none');
    const d = buildSmoothPath(pixelPoints);
    svg.innerHTML = `
      <path class="road-base" d="${d}" />
      <path class="road-line" d="${d}" />
    `;
    pathWrap.insertBefore(svg, pathWrap.firstChild);
  });
}

// Smooth curve through a series of points using cubic beziers whose
// control points sit at the vertical midpoint of each segment — gives
// the classic winding "road" S-curve between alternating left/right
// nodes without needing a full spline library.
function buildSmoothPath(points) {
  if (points.length === 0) return '';
  let d = `M ${points[0].x},${points[0].y}`;
  for (let i = 1; i < points.length; i++) {
    const prev = points[i - 1];
    const curr = points[i];
    const midY = (prev.y + curr.y) / 2;
    d += ` C ${prev.x},${midY} ${curr.x},${midY} ${curr.x},${curr.y}`;
  }
  return d;
}

