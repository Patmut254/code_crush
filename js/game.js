// ---------------- trace-to-spell input ----------------

let currentPath = [];
let dragging = false;

function attachPointerHandlers(board) {
  board.addEventListener('pointerdown', onPointerDown);
  board.addEventListener('pointermove', onPointerMove);
  window.addEventListener('pointerup', onPointerUp);
}

function tileIndexFromPoint(x, y) {
  const el = document.elementFromPoint(x, y);
  if (!el || !el.classList.contains('tile')) return null;
  return parseInt(el.dataset.index, 10);
}

function isAdjacent(a, b, size) {
  const ra = Math.floor(a / size), ca = a % size;
  const rb = Math.floor(b / size), cb = b % size;
  return Math.abs(ra - rb) <= 1 && Math.abs(ca - cb) <= 1 && a !== b;
}

function onPointerDown(e) {
  const idx = tileIndexFromPoint(e.clientX, e.clientY);
  if (idx === null) return;
  dragging = true;
  currentPath = [idx];
  updateSelectionUI();
}

function onPointerMove(e) {
  if (!dragging) return;
  const idx = tileIndexFromPoint(e.clientX, e.clientY);
  if (idx === null) return;

  const last = currentPath[currentPath.length - 1];
  if (idx === last) return;

  // allow backtracking by one step
  if (currentPath.length > 1 && idx === currentPath[currentPath.length - 2]) {
    currentPath.pop();
    updateSelectionUI();
    return;
  }

  if (currentPath.includes(idx)) return;
  if (!isAdjacent(last, idx, activeBoard.size)) return;

  currentPath.push(idx);
  updateSelectionUI();
}

function onPointerUp() {
  if (!dragging) return;
  dragging = false;
  submitPath();
}

function updateSelectionUI() {
  tilesEls.forEach(t => t.classList.remove('selected'));
  currentPath.forEach(i => tilesEls[i].classList.add('selected'));
  drawPathLine();
}

function drawPathLine() {
  const svg = document.getElementById('path-svg');
  const board = document.getElementById('board');
  if (currentPath.length < 2) { svg.innerHTML = ''; return; }

  const boardRect = board.getBoundingClientRect();
  const points = currentPath.map(i => {
    const el = tilesEls[i];
    const r = el.getBoundingClientRect();
    const x = r.left - boardRect.left + r.width / 2;
    const y = r.top - boardRect.top + r.height / 2;
    return `${x},${y}`;
  });

  svg.setAttribute('viewBox', `0 0 ${boardRect.width} ${boardRect.height}`);
  svg.innerHTML = `<path d="M ${points.join(' L ')}" />`;
}

function submitPath() {
  const word = currentPath.map(i => activeBoard.letters[i]).join('');
  const reversed = word.split('').reverse().join('');

  const match = activeLevel.milestones.find(m =>
    !foundWords.has(m) && (m === word || m === reversed)
  );

  if (match) {
    handleMilestoneFound(match);
  } else if (currentPath.length >= 2) {
    handleInvalidWord();
  }

  currentPath = [];
  updateSelectionUI();
}

