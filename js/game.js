// 5. BONUS / CHAIN-REACTION FEEDBACK
// ---------------------------------------------------------------

function handleMilestoneFound(word) {
  foundWords.add(word);
  comboCount++;

  const path = activeBoard.wordPaths[word];
  path.forEach(i => {
    tilesEls[i].classList.add('found');
    tilesEls[i].classList.add('pop');
    setTimeout(() => tilesEls[i].classList.remove('pop'), 400);
  });

  const chip = document.querySelector(`.milestone-chip[data-word="${word}"]`);
  if (chip) chip.classList.add('found');

  const gained = 10 * word.length * comboCount;
  score += gained;
  document.getElementById('score-value').textContent = score;

  triggerBonusEffect(word.length, path);
  updateComboDisplay();
  playTone(520 + word.length * 20, 0.12);

  if (!save.wordsDiscovered.includes(word)) save.wordsDiscovered.push(word);

  showToast(WORD_FACTS[word] ? `${word} \u2014 ${WORD_FACTS[word]}` : `${word}!`);

  if (foundWords.size === activeLevel.milestones.length) {
    setTimeout(completeLevel, 500);
  }
}

function handleInvalidWord() {
  wrongAttempts++;
  comboCount = 0;
  updateComboDisplay();
  currentPath.forEach(i => {
    tilesEls[i].classList.add('shake');
    setTimeout(() => tilesEls[i].classList.remove('shake'), 350);
  });
  playTone(160, 0.1);
}

function updateComboDisplay() {
  const el = document.getElementById('combo-display');
  const labels = ['', 'Good!', 'Nice!', 'Great!', 'Awesome!', 'Code Master!'];
  if (comboCount <= 0) { el.textContent = ''; return; }
  el.textContent = labels[Math.min(comboCount, 5)] + (comboCount > 1 ? ` x${comboCount}` : '');
  el.classList.remove('pop');
  void el.offsetWidth;
  el.classList.add('pop');
}

// small words -> subtle flash; long words / high combo -> bigger burst
function triggerBonusEffect(wordLength, path) {
  const flash = document.getElementById('board-flash');
  flash.classList.remove('go');
  void flash.offsetWidth;
  flash.classList.add('go');

  const intensity = Math.min(24, wordLength * 2 + comboCount * 2);
  const layer = document.getElementById('particle-layer');
  const originTile = tilesEls[path[path.length - 1]];
  const originRect = originTile.getBoundingClientRect();
  const layerRect = layer.getBoundingClientRect();
  const originX = originRect.left - layerRect.left + originRect.width / 2;
  const originY = originRect.top - layerRect.top + originRect.height / 2;

  for (let i = 0; i < intensity; i++) {
    const p = document.createElement('div');
    p.className = 'particle';
    const angle = Math.random() * Math.PI * 2;
    const dist = 40 + Math.random() * 70;
    p.style.setProperty('--px', Math.cos(angle) * dist + 'px');
    p.style.setProperty('--py', Math.sin(angle) * dist + 'px');
    p.style.left = originX + 'px';
    p.style.top = originY + 'px';
    p.style.background = wordLength >= 8 ? 'var(--world-accent)' : 'var(--gold)';
    layer.appendChild(p);
    setTimeout(() => p.remove(), 750);
  }
}

// tiny WebAudio beep — no external assets needed
let audioCtx = null;
function playTone(freq, duration) {
  if (!save.settings.sound) return;
  try {
    audioCtx = audioCtx || new (window.AudioContext || window.webkitAudioContext)();
    const osc = audioCtx.createOscillator();
    const gain = audioCtx.createGain();
    osc.frequency.value = freq;
    osc.type = 'sine';
    gain.gain.setValueAtTime(0.08, audioCtx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + duration);
    osc.connect(gain).connect(audioCtx.destination);
    osc.start();
    osc.stop(audioCtx.currentTime + duration);
  } catch (e) { /* audio not available — fail silently */ }
}

