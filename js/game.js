function computeStars() {
  if (wrongAttempts <= 2 && hintsUsedThisLevel === 0) return 3;
  if (wrongAttempts <= 5 && hintsUsedThisLevel <= 1) return 2;
  return 1;
}

function completeLevel() {
  const stars = computeStars();
  const coinsEarned = 15 + stars * 10;
  save.coins += coinsEarned;

  if (!activeLevel.isDaily) {
    const prev = save.results[activeLevel.id];
    save.results[activeLevel.id] = {
      stars: Math.max(stars, prev ? prev.stars : 0),
      score,
      hintsUsed: hintsUsedThisLevel
    };
    if (activeLevel.id === save.unlockedLevel && save.unlockedLevel < LEVELS.length) {
      save.unlockedLevel = activeLevel.id + 1;
    }
  } else {
    save.lastDaily = todayKey();
    save.dailyStreak += 1;
  }

  persistSave();
  checkAchievements();
  showLevelCompleteModal(stars, coinsEarned);
}

function animateNumber(el, from, to, duration) {
  const start = performance.now();
  function frame(now) {
    const t = Math.min(1, (now - start) / duration);
    const eased = 1 - Math.pow(1 - t, 3);
    el.textContent = Math.round(from + (to - from) * eased);
    if (t < 1) requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
}

function showLevelCompleteModal(stars, coinsEarned) {
  document.getElementById('complete-title').textContent =
    activeLevel.isDaily ? 'Daily Complete!' : 'Level Complete!';

  const starEls = document.querySelectorAll('#complete-stars .star');
  starEls.forEach((el, i) => {
    el.classList.remove('lit');
    if (i < stars) {
      setTimeout(() => el.classList.add('lit'), 150 + i * 180);
    }
  });

  animateNumber(document.getElementById('complete-coins'), 0, coinsEarned, 700);
  animateNumber(document.getElementById('complete-score'), 0, score, 700);

  const nextBtn = document.getElementById('btn-next-level');
  const hasNext = !activeLevel.isDaily && LEVELS.some(l => l.id === activeLevel.id + 1);
  nextBtn.style.display = hasNext ? 'inline-flex' : 'none';

  document.getElementById('modal-complete').classList.add('show');
  burstConfetti(document.getElementById('confetti-target'), { count: stars === 3 ? 130 : 80 });
  playTone(660, 0.15);
  setTimeout(() => playTone(880, 0.18), 150);
}

