document.getElementById('btn-hint').addEventListener('click', () => {
  const cost = 20;
  if (save.coins < cost) { showToast('Not enough coins for a hint'); return; }
  const remaining = activeLevel.milestones.filter(m => !foundWords.has(m));
  if (remaining.length === 0) return;

  save.coins -= cost;
  hintsUsedThisLevel++;
  persistSave();

  const word = remaining[0];
  const path = activeBoard.wordPaths[word];
  path.forEach((cellIndex, step) => {
    setTimeout(() => {
      tilesEls[cellIndex].classList.add('selected');
      setTimeout(() => tilesEls[cellIndex].classList.remove('selected'), 350);
    }, step * 120);
  });
  showToast(`Hint: watch the glowing path for ${word}`);
});

